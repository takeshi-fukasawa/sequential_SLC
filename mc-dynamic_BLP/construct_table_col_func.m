function col=construct_table_col_func(times_all,count_obj_eval_all,count_G_eval_all,iter_all,non_conv_all)
    col=[results_time_dist_func(sum(times_all,2)),...
            mean(count_obj_eval_all(:),'omitnan'),...
            mean(count_G_eval_all(:),'omitnan'),...
            mean(iter_all(:)+1),...
            mean(1-min(non_conv_all,[],2))*100,mean(1-non_conv_all(:))*100];
end